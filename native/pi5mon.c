typedef struct { int pid; unsigned long long ticks; unsigned long rss; char comm[20]; } proc_t;
typedef struct { char id[13]; unsigned long long usec; unsigned long long anon; } dk_t;
typedef struct { char name[16]; unsigned long long rx, tx; } if_t;
typedef struct { char name[16]; unsigned long long rd, wr; } disk_t; /* sectors */

typedef struct {
    double uptime;
    int ncpu; /* cores, without the aggregate line */
    unsigned long long cpu_busy[MAX_CPU + 1], cpu_all[MAX_CPU + 1]; /* [0] = aggregate */
    int nif; if_t ifs[MAX_IF];
    int ndisk; disk_t disks[MAX_DISK];
    int nproc; proc_t procs[MAX_PROC];
    int ndk; dk_t dks[MAX_DK];
} fast_t;

typedef struct {
    char host[64];
    double load[3]; int threads;
    unsigned long long mem_total, mem_avail, mem_free, buffers, cached, swap_total, swap_free;
    int temp_cpu, temp_rp1, fan_rpm, pwm, uv_now; /* milli-degC, rpm, 0-255 */
    unsigned long thr;
    int nfreq; int freq[MAX_CPU]; /* kHz */
    int ndf; struct { char mount[24]; unsigned long long total, used; } df[4];
    int has_thr, has_fan, has_rp1;
} slow_t;

