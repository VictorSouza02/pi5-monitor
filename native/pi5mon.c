static long long now_ms(void) {
    struct timeval tv;
    gettimeofday(&tv, 0);
    return (long long)tv.tv_sec * 1000 + tv.tv_usec / 1000;
}

/* ---------- growable output buffer ---------- */

typedef struct { char* p; size_t n, cap; } buf_t;

static void b_need(buf_t* b, size_t add) {
    if (b->n + add + 1 <= b->cap) return;
    size_t c = b->cap ? b->cap : 4096;
    while (c < b->n + add + 1) c *= 2;
    b->p = realloc(b->p, c);
    b->cap = c;
}
static void b_add(buf_t* b, const char* s, size_t n) { b_need(b, n); memcpy(b->p + b->n, s, n); b->n += n; b->p[b->n] = 0; }
static void b_puts(buf_t* b, const char* s) { b_add(b, s, strlen(s)); }
static void b_printf(buf_t* b, const char* fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    int k = vsnprintf(0, 0, fmt, ap);
    va_end(ap);
    if (k <= 0) return;
    b_need(b, (size_t)k);
    va_start(ap, fmt);
    vsnprintf(b->p + b->n, (size_t)k + 1, fmt, ap);
    va_end(ap);
    b->n += (size_t)k;
}
static void b_str(buf_t* b, const char* s) { /* JSON string literal */
    b_need(b, strlen(s) * 2 + 2);
    b->p[b->n++] = '"';
    for (; *s; s++) {
        unsigned char c = (unsigned char)*s;
        if (c == '"' || c == '\\') { b->p[b->n++] = '\\'; b->p[b->n++] = (char)c; }
        else if (c >= 0x20) b->p[b->n++] = (char)c;
    }
    b->p[b->n++] = '"';
    b->p[b->n] = 0;
}

