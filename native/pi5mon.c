static unsigned long long u64(const char** s) {
    const char* p = *s;
    while (*p == ' ' || *p == '\t') p++;
    unsigned long long v = 0;
    while (*p >= '0' && *p <= '9') v = v * 10 + (unsigned)(*p++ - '0');
    *s = p;
    return v;
}

static int starts(const char* s, const char* pre) { return strncmp(s, pre, strlen(pre)) == 0; }

/* Parse one /proc/<pid>/stat line into p. */
static int parse_proc(const char* line, proc_t* p) {
    const char* lp = strchr(line, '(');
    const char* rp = strrchr(line, ')');
    if (!lp || !rp || rp < lp) return 0;
    p->pid = atoi(line);
    size_t n = (size_t)(rp - lp - 1);
    if (n >= sizeof p->comm) n = sizeof p->comm - 1;
    memcpy(p->comm, lp + 1, n);
    p->comm[n] = 0;
    /* fields after ')': [0]=state(3) ... utime=14 -> [11], stime=15 -> [12], rss=24 -> [21] */
    const char* s = rp + 2;
    int f = 0;
    unsigned long long ut = 0, st = 0, rss = 0;
    while (*s && f <= 21) {
        if (f == 11) ut = strtoull(s, 0, 10);
        else if (f == 12) st = strtoull(s, 0, 10);
        else if (f == 21) rss = strtoull(s, 0, 10);
        while (*s && *s != ' ') s++;
        while (*s == ' ') s++;
        f++;
    }
    p->ticks = ut + st;
    p->rss = (unsigned long)rss;
    return 1;
}

/* Walk the collector output. Sections start with "@name" (own markers) or "==> path <=="
 * (headers printed by `head` for multiple files). After "@@2" the fast block repeats into b. */
static void parse_output(char* text, fast_t* a, fast_t* b, slow_t* sl, int* has_b) {
    memset(a, 0, sizeof *a);
    memset(sl, 0, sizeof *sl);
    memset(g_hw, 0, sizeof g_hw);
    *has_b = 0;
    fast_t* f = a;
    char sec[128] = "";
    int dk_cpu_i = 0, dk_mem_i = 0, df_hdr = 0;
    char* save = 0;
    for (char* line = strtok_r(text, "\n", &save); line; line = strtok_r(0, "\n", &save)) {
        if (line[0] == '@') {
            if (strcmp(line, "@@2") == 0) {
                f = b; memset(b, 0, sizeof *b); *has_b = 1; dk_cpu_i = 0;
            }
            snprintf(sec, sizeof sec, "%s", line);
            df_hdr = 1;
            continue;
        }
        if (starts(line, "==> ")) {
            char* e = strstr(line, " <==");
            if (e) *e = 0;
            snprintf(sec, sizeof sec, "%s", line + 4);
            continue;
        }
        if (strcmp(sec, "@ids") == 0) {
            f->ndk = 0;
            for (char* p = strstr(line, "docker-"); p && f->ndk < MAX_DK; p = strstr(p + 7, "docker-")) {
                if (strlen(p) < 7 + 12 || p[7] == '*') break;
                memcpy(f->dks[f->ndk].id, p + 7, 12);
                f->dks[f->ndk].id[12] = 0;
                f->ndk++;
            }
        } else if (strcmp(sec, "@dcpu") == 0) {
            if (starts(line, "usage_usec") && dk_cpu_i < f->ndk) { const char* s = line + 10; f->dks[dk_cpu_i++].usec = u64(&s); }
        } else if (strcmp(sec, "@dmem") == 0) {
            if (starts(line, "anon ") && dk_mem_i < a->ndk) { const char* s = line + 4; a->dks[dk_mem_i++].anon = u64(&s); }
        } else if (strcmp(sec, "@stat") == 0) {
            if (starts(line, "cpu")) {
                int idx = line[3] == ' ' ? 0 : atoi(line + 3) + 1;
                if (idx > MAX_CPU) continue;
                const char* s = line + 3;
                while (*s && *s != ' ') s++;
                unsigned long long v[10] = {0}, all = 0;
                for (int i = 0; i < 10; i++) { v[i] = u64(&s); }
                for (int i = 0; i < 8; i++) all += v[i]; /* guest time is already in user */
                f->cpu_all[idx] = all;
                f->cpu_busy[idx] = all - v[3] - v[4]; /* minus idle and iowait */
                if (idx > f->ncpu) f->ncpu = idx;
            }
        } else if (strcmp(sec, "@thr") == 0) {
            char* e = strchr(line, '=');
            if (e) { sl->thr = strtoul(e + 1, 0, 16); sl->has_thr = 1; }
        } else if (strcmp(sec, "@df") == 0) {
            if (df_hdr) { df_hdr = 0; continue; }
            if (sl->ndf < 4) {
                char fs[64], mnt[64];
                unsigned long long tot, used, avail;
                int cap;
                if (sscanf(line, "%63s %llu %llu %llu %d%% %63s", fs, &tot, &used, &avail, &cap, mnt) == 6) {
                    snprintf(sl->df[sl->ndf].mount, sizeof sl->df[0].mount, "%s", mnt);
                    sl->df[sl->ndf].total = tot * 1024;
                    sl->df[sl->ndf].used = used * 1024;
                    sl->ndf++;
                }
            }
        } else if (strcmp(sec, "/proc/uptime") == 0) {
            f->uptime = strtod(line, 0);
        } else if (strcmp(sec, "/proc/net/dev") == 0) {
            char* c = strchr(line, ':');
            if (!c || f->nif >= MAX_IF) continue;
            *c = 0;
            char* nm = line;
            while (*nm == ' ') nm++;
            if (!strcmp(nm, "lo") || starts(nm, "veth") || starts(nm, "br-") || starts(nm, "docker")) continue;
            const char* s = c + 1;
            unsigned long long v[9];
            for (int i = 0; i < 9; i++) v[i] = u64(&s);
            if (v[0] == 0 && v[8] == 0) continue; /* never used (eth0 unplugged) */
            if_t* it = &f->ifs[f->nif++];
            snprintf(it->name, sizeof it->name, "%s", nm);
            it->rx = v[0];
            it->tx = v[8];
        } else if (strcmp(sec, "/proc/diskstats") == 0) {
            unsigned maj, mnr;
            char nm[32];
            unsigned long long rdc, rdm, rds, rdt, wrc, wrm, wrs;
            if (sscanf(line, " %u %u %31s %llu %llu %llu %llu %llu %llu %llu", &maj, &mnr, nm, &rdc, &rdm, &rds, &rdt, &wrc, &wrm, &wrs) != 10) continue;
            int whole = (starts(nm, "mmcblk") && !strchr(nm + 6, 'p')) || (starts(nm, "nvme") && !strchr(nm + 4, 'p')) ||
                        (starts(nm, "sd") && strlen(nm) == 3);
            if (!whole || f->ndisk >= MAX_DISK) continue;
            disk_t* d = &f->disks[f->ndisk++];
            snprintf(d->name, sizeof d->name, "%s", nm);
            d->rd = rds;
            d->wr = wrs;
        } else if (starts(sec, "/proc/") && sec[6] >= '0' && sec[6] <= '9' && f->nproc < MAX_PROC) {
            if (parse_proc(line, &f->procs[f->nproc])) f->nproc++;
        } else if (strcmp(sec, "/etc/hostname") == 0) {
            snprintf(sl->host, sizeof sl->host, "%s", line);
        } else if (strcmp(sec, "/proc/loadavg") == 0) {
            sscanf(line, "%lf %lf %lf %*d/%d", &sl->load[0], &sl->load[1], &sl->load[2], &sl->threads);
        } else if (strcmp(sec, "/proc/meminfo") == 0) {
            const char* s = strchr(line, ':');
            if (!s) continue;
            s++;
            unsigned long long v = u64(&s) * 1024;
            if (starts(line, "MemTotal:")) sl->mem_total = v;
            else if (starts(line, "MemFree:")) sl->mem_free = v;
            else if (starts(line, "MemAvailable:")) sl->mem_avail = v;
            else if (starts(line, "Buffers:")) sl->buffers = v;
            else if (starts(line, "Cached:")) sl->cached = v;
            else if (starts(line, "SwapTotal:")) sl->swap_total = v;
            else if (starts(line, "SwapFree:")) sl->swap_free = v;
        } else if (strcmp(sec, "/sys/class/thermal/thermal_zone0/temp") == 0) {
            sl->temp_cpu = atoi(line);
        } else if (starts(sec, "/sys/class/hwmon/hwmon")) {
            int hi = atoi(sec + 22);
            if (hi < 0 || hi >= 8) continue;
            const char* leaf = strrchr(sec, '/') + 1;
            if (!strcmp(leaf, "name")) snprintf(g_hw[hi], sizeof g_hw[hi], "%s", line);
            else if (!strcmp(leaf, "temp1_input") && !strcmp(g_hw[hi], "rp1_adc")) { sl->temp_rp1 = atoi(line); sl->has_rp1 = 1; }
            else if (!strcmp(leaf, "fan1_input")) { sl->fan_rpm = atoi(line); sl->has_fan = 1; }
            else if (!strcmp(leaf, "pwm1")) sl->pwm = atoi(line);
            else if (!strcmp(leaf, "in0_lcrit_alarm")) sl->uv_now = atoi(line);
        } else if (starts(sec, "/sys/devices/system/cpu/cpu")) {
            int ci = atoi(sec + 27);
            if (ci >= 0 && ci < MAX_CPU) { sl->freq[ci] = atoi(line); if (ci + 1 > sl->nfreq) sl->nfreq = ci + 1; }
        }
    }
}

/* ---------- container names cache ---------- */

static void names_load(const char* host) {
    if (!strcmp(g_names_host, host)) return;
    snprintf(g_names_host, sizeof g_names_host, "%s", host);
    g_nnames = 0;
    char path[256];
    snprintf(path, sizeof path, "%s/names-%s.txt", g_dir, host);
    FILE* fp = fopen(path, "r");
    if (!fp) return;
    char line[128];
    while (g_nnames < MAX_NAMES && fgets(line, sizeof line, fp)) {
        char* sp = strchr(line, ' ');
        if (!sp || sp - line != 12) continue;
        line[strcspn(line, "\n")] = 0;
        memcpy(g_names[g_nnames].id, line, 12);
        g_names[g_nnames].id[12] = 0;
        snprintf(g_names[g_nnames].name, sizeof g_names[0].name, "%s", sp + 1);
        g_nnames++;
    }
    fclose(fp);
}

static const char* name_of(const char* id) {
    for (int i = 0; i < g_nnames; i++)
        if (!strcmp(g_names[i].id, id)) return g_names[i].name;
    return 0;
}

/* Merge "@names" output ("<path>/<64hex>/config.v2.json:"Name":"/x"") into the cache file. */
static void names_merge(char* text, const char* host) {
    int changed = 0;
    char* save = 0;
    for (char* line = strtok_r(text, "\n", &save); line; line = strtok_r(0, "\n", &save)) {
        char* cfg = strstr(line, "/config.v2.json:");
        char* nm = strstr(line, "\"Name\":\"/");
        if (!cfg || !nm || cfg - line < 65) continue;
        char id[13];
        memcpy(id, cfg - 64, 12);
        id[12] = 0;
        nm += 9;
        char* q = strchr(nm, '"');
        if (q) *q = 0;
        /* Swarm task names end in ".<slot>.<25-char task id>"; keep the service part. */
        char* d1 = strchr(nm, '.');
        if (d1) { char* d2 = strchr(d1 + 1, '.'); if (d2 && strlen(d2 + 1) == 25) *d1 = 0; }
        int i;
        for (i = 0; i < g_nnames; i++) if (!strcmp(g_names[i].id, id)) break;
        if (i == g_nnames) { if (g_nnames >= MAX_NAMES) continue; g_nnames++; }
        memcpy(g_names[i].id, id, 13);
        snprintf(g_names[i].name, sizeof g_names[0].name, "%s", nm);
        changed = 1;
    }
    if (!changed) return;
    char path[256], tmp[260];
    snprintf(path, sizeof path, "%s/names-%s.txt", g_dir, host);
    snprintf(tmp, sizeof tmp, "%s.new", path);
    FILE* fp = fopen(tmp, "w");
    if (!fp) return;
    for (int i = 0; i < g_nnames; i++) fprintf(fp, "%s %s\n", g_names[i].id, g_names[i].name);
    fclose(fp);
    rename(tmp, path);
}

/* ---------- ssh ---------- */

static int valid_ip(const char* s) {
    struct in_addr a;
    return strlen(s) < 16 && inet_pton(AF_INET, s, &a) == 1;
}

/* Run the collector on host with request words req. stdout -> out, stderr tail -> err. */
static int run_ssh(const char* host, const char* req, buf_t* out, char* err, size_t errsz, int timeout_ms) {
    char key[256], kh[256], dest[80];
    snprintf(key, sizeof key, "%s/id_ed25519", g_dir);
    snprintf(kh, sizeof kh, "UserKnownHostsFile=%s/known_hosts", g_dir);
    snprintf(dest, sizeof dest, "root@%s", host);
    char* argv[] = {"ssh", "-i", key, "-F", "/dev/null", "-T", "-a", "-x",
                    "-o", "BatchMode=yes", "-o", "ConnectTimeout=4", "-o", "StrictHostKeyChecking=no",
                    "-o", kh, "-o", "Ciphers=chacha20-poly1305@openssh.com",
                    "-o", "KexAlgorithms=ecdh-sha2-nistp256", "-o", "HostKeyAlgorithms=ecdsa-sha2-nistp256",
                    "-o", "Compression=no", "-o", "LogLevel=ERROR", dest, (char*)req, 0};
    int po[2], pe[2];
    if (pipe(po) || pipe(pe)) { snprintf(err, errsz, "pipe failed"); return -1; }
    posix_spawn_file_actions_t fa;
    posix_spawn_file_actions_init(&fa);
    posix_spawn_file_actions_addopen(&fa, 0, "/dev/null", O_RDONLY, 0);
    posix_spawn_file_actions_adddup2(&fa, po[1], 1);
    posix_spawn_file_actions_adddup2(&fa, pe[1], 2);
    posix_spawn_file_actions_addclose(&fa, po[0]);
    posix_spawn_file_actions_addclose(&fa, pe[0]);
    pid_t pid;
    int r = posix_spawn(&pid, "/usr/bin/ssh", &fa, 0, argv, environ);
    posix_spawn_file_actions_destroy(&fa);
    close(po[1]);
    close(pe[1]);
    if (r) { close(po[0]); close(pe[0]); snprintf(err, errsz, "spawn ssh: %s", strerror(r)); return -1; }
    size_t en = 0;
    err[0] = 0;
    long long deadline = now_ms() + timeout_ms;
    struct pollfd pf[2] = {{po[0], POLLIN, 0}, {pe[0], POLLIN, 0}};
    int open_n = 2, timed_out = 0;
    while (open_n > 0) {
        long long left = deadline - now_ms();
        if (left <= 0) { timed_out = 1; break; }
        if (poll(pf, 2, (int)left) <= 0) continue;
        for (int i = 0; i < 2; i++) {
            if (pf[i].fd < 0 || !(pf[i].revents & (POLLIN | POLLHUP | POLLERR))) continue;
            char tmp[16384];
            ssize_t k = read(pf[i].fd, tmp, sizeof tmp);
            if (k <= 0) { close(pf[i].fd); pf[i].fd = -1; open_n--; continue; }
            if (i == 0) b_add(out, tmp, (size_t)k);
            else if (en + 1 < errsz) {
                size_t c = (size_t)k < errsz - 1 - en ? (size_t)k : errsz - 1 - en;
                memcpy(err + en, tmp, c);
                en += c;
                err[en] = 0;
            }
        }
    }
    for (int i = 0; i < 2; i++) if (pf[i].fd >= 0) close(pf[i].fd);
    if (timed_out) kill(pid, SIGKILL);
    int st = 0;
    waitpid(pid, &st, 0);
    if (timed_out) { snprintf(err, errsz, "timeout talking to %s", host); return -1; }
    for (size_t i = 0; i < en; i++) if (err[i] == '\r' || err[i] == '\n') err[i] = ' ';
    if (!WIFEXITED(st) || WEXITSTATUS(st) != 0) {
        if (!err[0]) snprintf(err, errsz, "ssh exit %d", WIFEXITED(st) ? WEXITSTATUS(st) : -1);
        return -1;
    }
    return 0;
}

/* ---------- stats JSON ---------- */

static int cmp_pid(const void* x, const void* y) { return ((const proc_t*)x)->pid - ((const proc_t*)y)->pid; }

typedef struct { int i; double cpu; unsigned long long mem; } rank_t;
static int cmp_rank(const void* x, const void* y) { /* CPU desc, then memory desc */
    const rank_t *a = x, *b = y;
    if (a->cpu != b->cpu) return a->cpu < b->cpu ? 1 : -1;
    return a->mem < b->mem ? 1 : a->mem > b->mem ? -1 : 0;
}

static double pct(unsigned long long d, unsigned long long all) { return all ? 100.0 * (double)d / (double)all : 0; }

/* Rates between samples p (older) and c (newer). */
static void emit_rates(buf_t* o, fast_t* p, fast_t* c, slow_t* sl) {
    double dt = c->uptime - p->uptime;
    if (dt <= 0.05) dt = 0.05;
    b_printf(o, ",\"dt\":%.2f", dt);
    b_printf(o, ",\"cpu\":%.1f,\"cores\":[", pct(c->cpu_busy[0] - p->cpu_busy[0], c->cpu_all[0] - p->cpu_all[0]));
    for (int i = 1; i <= c->ncpu; i++)
        b_printf(o, "%s%.1f", i > 1 ? "," : "", pct(c->cpu_busy[i] - p->cpu_busy[i], c->cpu_all[i] - p->cpu_all[i]));
    b_puts(o, "],\"net\":[");
    for (int i = 0; i < c->nif; i++) {
        unsigned long long rx = 0, tx = 0;
        for (int j = 0; j < p->nif; j++)
            if (!strcmp(p->ifs[j].name, c->ifs[i].name)) { rx = c->ifs[i].rx - p->ifs[j].rx; tx = c->ifs[i].tx - p->ifs[j].tx; }
        b_printf(o, "%s[", i ? "," : "");
        b_str(o, c->ifs[i].name);
        b_printf(o, ",%.0f,%.0f,%llu,%llu]", rx / dt, tx / dt, c->ifs[i].rx, c->ifs[i].tx);
    }
    b_puts(o, "],\"io\":[");
    for (int i = 0; i < c->ndisk; i++) {
        unsigned long long rd = 0, wr = 0;
        for (int j = 0; j < p->ndisk; j++)
            if (!strcmp(p->disks[j].name, c->disks[i].name)) { rd = c->disks[i].rd - p->disks[j].rd; wr = c->disks[i].wr - p->disks[j].wr; }
        b_printf(o, "%s[", i ? "," : "");
        b_str(o, c->disks[i].name);
        b_printf(o, ",%.0f,%.0f]", rd * 512.0 / dt, wr * 512.0 / dt);
    }
    /* Containers: % of one core, like `docker stats`. Memory = anon (from the first sample). */
    b_puts(o, "],\"dk\":[");
    static rank_t rk[MAX_PROC];
    int nr = 0;
    for (int i = 0; i < c->ndk; i++) {
        double cpu = 0;
        for (int j = 0; j < p->ndk; j++)
            if (!strcmp(p->dks[j].id, c->dks[i].id)) { cpu = (double)(c->dks[i].usec - p->dks[j].usec) / (dt * 1e4); break; }
        rk[nr].i = i; rk[nr].cpu = cpu; rk[nr].mem = 0;
        for (int j = 0; j < g_a.ndk; j++) if (!strcmp(g_a.dks[j].id, c->dks[i].id)) { rk[nr].mem = g_a.dks[j].anon; break; }
        nr++;
    }
    qsort(rk, (size_t)nr, sizeof rk[0], cmp_rank);
    for (int k = 0; k < nr; k++) {
        dk_t* d = &c->dks[rk[k].i];
        unsigned long long anon = rk[k].mem;
        const char* nm = name_of(d->id);
        b_printf(o, "%s[", k ? "," : "");
        b_str(o, nm ? nm : d->id);
        b_printf(o, ",%.1f,%llu]", rk[k].cpu, anon);
    }
    /* Top processes by CPU over the interval (% of one core, like top). */
    b_puts(o, "],\"top\":[");
    qsort(p->procs, (size_t)p->nproc, sizeof(proc_t), cmp_pid);
    nr = 0;
    for (int i = 0; i < c->nproc; i++) {
        proc_t key = {.pid = c->procs[i].pid};
        proc_t* q = bsearch(&key, p->procs, (size_t)p->nproc, sizeof(proc_t), cmp_pid);
        double cpu = q && c->procs[i].ticks >= q->ticks ? (double)(c->procs[i].ticks - q->ticks) / dt : 0;
        rk[nr].i = i; rk[nr].cpu = cpu; rk[nr].mem = c->procs[i].rss; nr++;
    }
    qsort(rk, (size_t)nr, sizeof rk[0], cmp_rank);
    for (int k = 0; k < nr && k < 10; k++) {
        proc_t* pr = &c->procs[rk[k].i];
        b_printf(o, "%s[", k ? "," : "");
        b_str(o, pr->comm);
        b_printf(o, ",%d,%.1f,%lu]", pr->pid, rk[k].cpu, pr->rss * 4096UL);
    }
    b_printf(o, "],\"nproc\":%d", c->nproc);
    (void)sl;
}

static void handle_stats(buf_t* o, const char* host) {
    long long t0 = now_ms();
    int have_prev = !strcmp(g_prev_host, host) && t0 - g_prev_at < PREV_MAX_MS;
    buf_t out = {0};
    char err[512];
    if (run_ssh(host, have_prev ? "x" : "d", &out, err, sizeof err, SSH_TIMEOUT_MS)) {
        b_puts(o, "{\"err\":");
        b_str(o, err);
        b_puts(o, "}");
        free(out.p);
        return;
    }
    long long t1 = now_ms();
    int has_b = 0;
    parse_output(out.p ? out.p : (char*)"", &g_a, &g_b, &g_slow, &has_b);
    free(out.p);
    if (!g_a.uptime) { b_puts(o, "{\"err\":\"empty reply from collector\"}"); return; }

    /* Unknown container ids: one extra small ssh for their names (only when containers change). */
    names_load(host);
    char req[MAX_DK * 13 + 4] = "n";
    int unknown = 0;
    for (int i = 0; i < g_a.ndk; i++)
        if (!name_of(g_a.dks[i].id)) { strcat(req, " "); strcat(req, g_a.dks[i].id); unknown++; }
    if (unknown) {
        buf_t nb = {0};
        if (!run_ssh(host, unknown == g_a.ndk ? "n" : req, &nb, err, sizeof err, SSH_TIMEOUT_MS) && nb.p) names_merge(nb.p, host);
        free(nb.p);
    }

    slow_t* s = &g_slow;
    b_puts(o, "{\"host\":");
    b_str(o, s->host[0] ? s->host : host);
    b_printf(o, ",\"ip\":\"%s\",\"ssh_ms\":%lld,\"mode\":\"%s\",\"up\":%.0f", host, t1 - t0, have_prev ? "prev" : "double", g_a.uptime);
    b_printf(o, ",\"load\":[%.2f,%.2f,%.2f],\"threads\":%d", s->load[0], s->load[1], s->load[2], s->threads);
    b_printf(o, ",\"mem\":[%llu,%llu,%llu,%llu]", s->mem_total, s->mem_avail, s->buffers + s->cached, s->mem_free);
    b_printf(o, ",\"swap\":[%llu,%llu]", s->swap_total, s->swap_total - s->swap_free);
    b_printf(o, ",\"temp\":%.1f", s->temp_cpu / 1000.0);
    if (s->has_rp1) b_printf(o, ",\"rp1\":%.1f", s->temp_rp1 / 1000.0);
    if (s->has_fan) b_printf(o, ",\"fan\":%d,\"pwm\":%d", s->fan_rpm, s->pwm);
    if (s->has_thr) b_printf(o, ",\"thr\":%lu", s->thr);
    b_printf(o, ",\"uv\":%d,\"freq\":[", s->uv_now);
    for (int i = 0; i < s->nfreq; i++) b_printf(o, "%s%d", i ? "," : "", s->freq[i] / 1000);
    b_puts(o, "],\"df\":[");
    for (int i = 0; i < s->ndf; i++) {
        b_printf(o, "%s[", i ? "," : "");
        b_str(o, s->df[i].mount);
        b_printf(o, ",%llu,%llu]", s->df[i].total, s->df[i].used);
    }
    b_puts(o, "]");

    fast_t* newest = has_b ? &g_b : &g_a;
    if (has_b) emit_rates(o, &g_a, &g_b, s);
    else emit_rates(o, &g_prev, &g_a, s);
    b_puts(o, "}");
    memcpy(&g_prev, newest, sizeof g_prev);
    snprintf(g_prev_host, sizeof g_prev_host, "%s", host);
    g_prev_at = now_ms();
}

/* ---------- storage breakdown ---------- */

/* docker CLI sizes are decimal (units.HumanSize): "30.7GB", "28.67kB", "0B". */
static double human(const char* s) {
    char* e;
    double v = strtod(s, &e);
    switch (*e) {
    case 'k': case 'K': return v * 1e3;
    case 'M': return v * 1e6;
    case 'G': return v * 1e9;
    case 'T': return v * 1e12;
    default: return v;
    }
}

/* Heavy (~1-8 s on the Pi), so the result is cached in <dir>/disk-<ip>.json and only remeasured
 * on request (force=1) or when no measurement exists yet. */
static void handle_disk(buf_t* o, const char* host, int force) {
    char path[256];
    snprintf(path, sizeof path, "%s/disk-%s.json", g_dir, host);
    if (!force) {
        FILE* fp = fopen(path, "r");
        if (fp) {
            char tmp[1024];
            size_t n = fread(tmp, 1, sizeof tmp - 1, fp);
            fclose(fp);
            tmp[n] = 0;
            if (n) { b_puts(o, tmp); return; }
        }
    }
    buf_t out = {0};
    char err[512];
    if (run_ssh(host, "s", &out, err, sizeof err, DISK_TIMEOUT_MS) || !out.p) {
        b_puts(o, "{\"err\":");
        b_str(o, err[0] ? err : "no reply");
        b_puts(o, "}");
        free(out.p);
        return;
    }
    /* Images|30.7GB|0B (0%)|24|24  ->  "img":[size, reclaimable, total, active] */
    static const char* keys[][2] = {{"Images", "img"}, {"Containers", "ctr"}, {"Local Volumes", "vol"}, {"Build Cache", "bc"}};
    double v[4][4] = {{0}};
    double sc = 0;
    char sec[16] = "";
    char* save = 0;
    for (char* line = strtok_r(out.p, "\n", &save); line; line = strtok_r(0, "\n", &save)) {
        if (line[0] == '@') { snprintf(sec, sizeof sec, "%s", line); continue; }
        if (!strcmp(sec, "@sc")) { sc = strtod(line, 0) * 1024; continue; }
        char* f[5] = {0};
        int nf = 0;
        for (char* p = line; nf < 5; ) { f[nf++] = p; p = strchr(p, '|'); if (!p) break; *p++ = 0; }
        if (nf < 5) continue;
        for (int k = 0; k < 4; k++)
            if (!strcmp(f[0], keys[k][0])) { v[k][0] = human(f[1]); v[k][1] = human(f[2]); v[k][2] = atof(f[3]); v[k][3] = atof(f[4]); }
    }
    free(out.p);
    buf_t j = {0};
    struct timeval tv;
    gettimeofday(&tv, 0);
    b_printf(&j, "{\"at\":%ld", (long)tv.tv_sec);
    for (int k = 0; k < 4; k++) b_printf(&j, ",\"%s\":[%.0f,%.0f,%.0f,%.0f]", keys[k][1], v[k][0], v[k][1], v[k][2], v[k][3]);
    b_printf(&j, ",\"sc\":%.0f}", sc);
    char tmpp[260];
    snprintf(tmpp, sizeof tmpp, "%s.new", path);
    FILE* fp = fopen(tmpp, "w");
    if (fp) { fwrite(j.p, 1, j.n, fp); fclose(fp); rename(tmpp, path); }
    b_add(o, j.p, j.n);
    free(j.p);
}

/* ---------- LAN scan ---------- */

static const char* PI_OUI[] = {"88:a2:9e", "2c:cf:67", "d8:3a:dd", "dc:a6:32", "e4:5f:01", "b8:27:eb", "28:cd:c1", 0};

static int arp_lookup(uint32_t ip_be, char* mac, size_t macsz) {
    int mib[6] = {CTL_NET, PF_ROUTE, 0, AF_INET, NET_RT_FLAGS, RTF_LLINFO};
    size_t need = 0;
    if (sysctl(mib, 6, 0, &need, 0, 0) < 0 || !need) return 0;
    char* bufp = malloc(need);
    if (!bufp || sysctl(mib, 6, bufp, &need, 0, 0) < 0) { free(bufp); return 0; }
    int found = 0;
    for (char* p = bufp; p < bufp + need;) {
        struct rt_msghdr* rtm = (struct rt_msghdr*)p;
        struct sockaddr_in* sin = (struct sockaddr_in*)(rtm + 1);
        struct sockaddr_dl* sdl = (struct sockaddr_dl*)((char*)sin + ((sin->sin_len + 3) & ~3));
        if (sin->sin_addr.s_addr == ip_be && sdl->sdl_alen == 6) {
            unsigned char* m = (unsigned char*)LLADDR(sdl);
            snprintf(mac, macsz, "%02x:%02x:%02x:%02x:%02x:%02x", m[0], m[1], m[2], m[3], m[4], m[5]);
            found = 1;
            break;
        }
        if (!rtm->rtm_msglen) break;
        p += rtm->rtm_msglen;
    }
    free(bufp);
    return found;
}

#define SCAN_MAX 288
#define SCAN_MS 2500        /* unknown hosts: one connect, this long */
#define SCAN_KNOWN_MS 5000  /* known Pis: retried until this deadline */

static struct pollfd s_pf[SCAN_MAX];
static uint32_t s_ip[SCAN_MAX];
static int s_state[SCAN_MAX]; /* 0 connecting, 1 waiting banner, 2 ok, -1 dead, 3 retry pending */
static int s_known[SCAN_MAX], s_tries[SCAN_MAX];
static long long s_retry_at[SCAN_MAX];
static char s_banner[SCAN_MAX][48];

static void scan_open(int k) {
    s_pf[k].fd = -1; s_pf[k].revents = 0;
    int fd = socket(AF_INET, SOCK_STREAM, 0);
    if (fd < 0) { s_state[k] = -1; return; }
    fcntl(fd, F_SETFL, O_NONBLOCK);
    struct sockaddr_in sa = {.sin_len = sizeof sa, .sin_family = AF_INET, .sin_port = htons(22)};
    sa.sin_addr.s_addr = htonl(s_ip[k]);
    s_tries[k]++;
    if (connect(fd, (struct sockaddr*)&sa, sizeof sa) < 0 && errno != EINPROGRESS) { close(fd); s_state[k] = -1; return; }
    s_pf[k].fd = fd; s_pf[k].events = POLLOUT; s_state[k] = 0;
}

/* A failed known host gets another connect 400 ms later (Wi-Fi waking up, ARP not answered yet,
 * or iOS marking the host down for host_down_time after a miss), up to 3 tries. */
static void scan_fail(int k, long long now, long long known_end) {
    if (s_pf[k].fd >= 0) close(s_pf[k].fd);
    s_pf[k].fd = -1;
    if (s_known[k] && s_tries[k] < 3 && now + 400 < known_end) { s_state[k] = 3; s_retry_at[k] = now + 400; }
    else s_state[k] = -1;
}

/* known: comma-separated IPs the page has opened before; probed first and retried. */
static void handle_scan(buf_t* o, const char* known) {
    uint32_t me = 0, mask = 0;
    long long t0 = now_ms();
    for (;;) { /* right after wake-up en0 may not have its address yet */
        struct ifaddrs *ifa, *i;
        if (getifaddrs(&ifa) == 0) {
            for (i = ifa; i; i = i->ifa_next) {
                if (!i->ifa_addr || i->ifa_addr->sa_family != AF_INET || (i->ifa_flags & IFF_LOOPBACK) || !(i->ifa_flags & IFF_UP)) continue;
                me = ntohl(((struct sockaddr_in*)i->ifa_addr)->sin_addr.s_addr);
                mask = ntohl(((struct sockaddr_in*)i->ifa_netmask)->sin_addr.s_addr);
                if (!strcmp(i->ifa_name, "en0")) break;
            }
            freeifaddrs(ifa);
        }
        if (me || now_ms() - t0 > 3000) break;
        usleep(150000);
    }
    if (!me) { b_puts(o, "{\"err\":\"no Wi-Fi address\"}"); return; }
    if (mask < 0xFFFFFF00u) mask = 0xFFFFFF00u; /* scan at most the /24 around us */
    uint32_t net = me & mask, nhost = ~mask - 1;
    if (nhost > 254) nhost = 254;

    int n = 0;
    char kb[512];
    snprintf(kb, sizeof kb, "%s", known ? known : "");
    char* save = 0;
    for (char* t = strtok_r(kb, ",", &save); t && n < 16; t = strtok_r(0, ",", &save)) {
        struct in_addr a;
        if (inet_pton(AF_INET, t, &a) != 1) continue;
        s_ip[n] = ntohl(a.s_addr); s_known[n] = 1; s_tries[n] = 0; s_banner[n][0] = 0;
        n++;
    }
    int nknown = n;
    for (uint32_t h = 1; h <= nhost && n < SCAN_MAX; h++) {
        uint32_t ip = net | h;
        int dup = ip == me;
        for (int k = 0; k < nknown && !dup; k++) dup = s_ip[k] == ip;
        if (dup) continue;
        s_ip[n] = ip; s_known[n] = 0; s_tries[n] = 0; s_banner[n][0] = 0;
        n++;
    }
    for (int k = 0; k < n; k++) scan_open(k);

    long long start = now_ms(), end = start + SCAN_MS, known_end = start + (nknown ? SCAN_KNOWN_MS : SCAN_MS);
    for (;;) {
        long long now = now_ms(), wake = now + 1000;
        int active = 0;
        for (int k = 0; k < n; k++) {
            if (!s_known[k] && now >= end && (s_state[k] == 0 || s_state[k] == 1)) scan_fail(k, now, known_end);
            if (s_state[k] == 3 && now >= s_retry_at[k]) scan_open(k);
            if (s_state[k] == 0 || s_state[k] == 1) active = 1;
            if (s_state[k] == 3) { active = 1; if (s_retry_at[k] < wake) wake = s_retry_at[k]; }
        }
        if (!active || now >= known_end) break;
        long long lim = (now < end ? end : known_end);
        if (wake > lim) wake = lim;
        poll(s_pf, (nfds_t)n, (int)(wake > now ? wake - now : 0));
        now = now_ms();
        for (int k = 0; k < n; k++) {
            if (s_pf[k].fd < 0 || !s_pf[k].revents) continue;
            if (s_state[k] == 0) {
                int e = 0; socklen_t el = sizeof e;
                getsockopt(s_pf[k].fd, SOL_SOCKET, SO_ERROR, &e, &el);
                if (e || (s_pf[k].revents & (POLLERR | POLLHUP))) { scan_fail(k, now, known_end); continue; }
                s_state[k] = 1; s_pf[k].events = POLLIN;
            } else if (s_state[k] == 1) {
                ssize_t r = read(s_pf[k].fd, s_banner[k], sizeof s_banner[k] - 1);
                s_banner[k][r > 0 ? r : 0] = 0;
                s_banner[k][strcspn(s_banner[k], "\r\n")] = 0;
                close(s_pf[k].fd); s_pf[k].fd = -1; s_state[k] = 2;
            }
        }
    }
    for (int k = 0; k < n; k++) if (s_pf[k].fd >= 0) { if (s_state[k] == 1) s_state[k] = 2; close(s_pf[k].fd); s_pf[k].fd = -1; }

    b_puts(o, "{\"me\":");
    struct in_addr mi = {htonl(me)};
    b_str(o, inet_ntoa(mi));
    b_printf(o, ",\"ms\":%lld,\"hosts\":[", now_ms() - t0);
    int first = 1;
    for (int pass = 0; pass < 2; pass++) { /* Raspberry Pis first */
        for (int k = 0; k < n; k++) {
            if (s_state[k] != 2) continue;
            char mac[24] = "";
            arp_lookup(htonl(s_ip[k]), mac, sizeof mac);
            int pi = 0;
            for (int j = 0; PI_OUI[j]; j++) if (starts(mac, PI_OUI[j])) pi = 1;
            if (pi != (pass == 0)) continue;
            struct in_addr a = {htonl(s_ip[k])};
            b_puts(o, first ? "{\"ip\":" : ",{\"ip\":");
            first = 0;
            b_str(o, inet_ntoa(a));
            b_puts(o, ",\"mac\":");
            b_str(o, mac);
            b_printf(o, ",\"pi\":%d,\"known\":%d,\"banner\":", pi, s_known[k]);
            b_str(o, s_banner[k]);
            b_puts(o, "}");
        }
    }
    b_puts(o, "]}");
}

/* ---------- HTTP ---------- */

static void send_all(int fd, const char* p, size_t n) {
    while (n) {
        ssize_t k = write(fd, p, n);
        if (k <= 0) { if (k < 0 && errno == EINTR) continue; return; }
        p += k; n -= (size_t)k;
    }
}

static void reply(int fd, const char* status, const char* ctype, const char* extra, const char* body, size_t len) {
    char h[512];
    int k = snprintf(h, sizeof h, "HTTP/1.1 %s\r\nContent-Type: %s\r\nContent-Length: %zu\r\nConnection: close\r\n%s\r\n",
                     status, ctype, len, extra ? extra : "");
    send_all(fd, h, (size_t)k);
    if (len) send_all(fd, body, len);
}

static void query_get(const char* q, const char* key, char* out, size_t outsz) {
    out[0] = 0;
    size_t kl = strlen(key);
    for (const char* p = q; p && *p; p = strchr(p, '&') ? strchr(p, '&') + 1 : 0) {
        if (!strncmp(p, key, kl) && p[kl] == '=') {
            size_t n = strcspn(p + kl + 1, "& ");
            if (n >= outsz) n = outsz - 1;
            memcpy(out, p + kl + 1, n);
            out[n] = 0;
            return;
        }
    }
}

static void handle(int fd) {
    char req[4096];
    size_t n = 0;
    struct pollfd p = {fd, POLLIN, 0};
    while (n < sizeof req - 1) {
        if (poll(&p, 1, 3000) <= 0) return;
        ssize_t k = read(fd, req + n, sizeof req - 1 - n);
        if (k <= 0) return;
        n += (size_t)k;
        req[n] = 0;
        if (strstr(req, "\r\n\r\n")) break;
    }
    char method[8], path[512];
    if (sscanf(req, "%7s %511s", method, path) != 2) return;
    char* q = strchr(path, '?');
    if (q) *q++ = 0;
    const char* json = "application/json";
    const char* nocache = "Cache-Control: no-store\r\n";
    if (!strcmp(path, "/") || !strcmp(path, "/index.html")) {
        const char* inm = strstr(req, "If-None-Match: ");
        if (inm && !strncmp(inm + 15, "\"" INDEX_ETAG "\"", strlen(INDEX_ETAG) + 2)) {
            reply(fd, "304 Not Modified", "text/html", "ETag: \"" INDEX_ETAG "\"\r\n", 0, 0);
            return;
        }
        reply(fd, "200 OK", "text/html; charset=utf-8",
              "Content-Encoding: gzip\r\nCache-Control: no-cache\r\nETag: \"" INDEX_ETAG "\"\r\n",
              (const char*)index_gz, index_gz_len);
    } else if (!strcmp(path, "/api/stats")) {
        char host[64];
        query_get(q, "h", host, sizeof host);
        buf_t o = {0};
        if (!valid_ip(host)) b_puts(&o, "{\"err\":\"bad host\"}");
        else handle_stats(&o, host);
        reply(fd, "200 OK", json, nocache, o.p, o.n);
        free(o.p);
    } else if (!strcmp(path, "/api/disk")) {
        char host[64], force[4];
        query_get(q, "h", host, sizeof host);
        query_get(q, "force", force, sizeof force);
        buf_t o = {0};
        if (!valid_ip(host)) b_puts(&o, "{\"err\":\"bad host\"}");
        else handle_disk(&o, host, force[0] == '1');
        reply(fd, "200 OK", json, nocache, o.p, o.n);
        free(o.p);
    } else if (!strcmp(path, "/api/scan")) {
        char known[512];
        query_get(q, "k", known, sizeof known);
        buf_t o = {0};
        handle_scan(&o, known);
        reply(fd, "200 OK", json, nocache, o.p, o.n);
        free(o.p);
    } else {
        reply(fd, "404 Not Found", "text/plain", 0, "not found", 9);
    }
}

int main(int argc, char** argv) {
    if (argc > 1) g_dir = argv[1];
    int port = argc > 2 ? atoi(argv[2]) : 8899;
    int lan = argc > 3 && !strcmp(argv[3], "lan");
    signal(SIGPIPE, SIG_IGN);
    /* launchd daemons on iOS 9 get a tiny jetsam limit; lift it (needs root). */
    memorystatus_control(5 /* SET_JETSAM_HIGH_WATER_MARK */, getpid(), (unsigned int)-1, 0, 0);
    struct rlimit rl = {1024, 1024};
    setrlimit(RLIMIT_NOFILE, &rl); /* the scan opens ~254 sockets at once */

    int* fds = 0;
    size_t nfds = 0;
    int ls = -1;
    if (!lan && launch_activate_socket("Listener", &fds, &nfds) == 0 && nfds > 0) {
        ls = fds[0];
    } else {
        ls = socket(AF_INET, SOCK_STREAM, 0);
        int one = 1;
        setsockopt(ls, SOL_SOCKET, SO_REUSEADDR, &one, sizeof one);
        struct sockaddr_in sa = {.sin_len = sizeof sa, .sin_family = AF_INET, .sin_port = htons((uint16_t)port)};
        sa.sin_addr.s_addr = htonl(lan ? INADDR_ANY : INADDR_LOOPBACK);
        if (bind(ls, (struct sockaddr*)&sa, sizeof sa) || listen(ls, 16)) { perror("bind"); return 1; }
        fprintf(stderr, "[pi5mon] listening on %s:%d (no launchd socket)\n", lan ? "0.0.0.0" : "127.0.0.1", port);
    }
    for (;;) {
        struct pollfd p = {ls, POLLIN, 0};
        int r = poll(&p, 1, IDLE_SEC * 1000);
        if (r == 0) return 0; /* idle: launchd starts us again on the next connection */
        if (r < 0) { if (errno == EINTR) continue; return 1; }
        int c = accept(ls, 0, 0);
        if (c < 0) continue;
        handle(c);
        close(c);
    }
}
